export function tr(l: Lang, s: string): string {
  if (l === 'id') return s
  const e = D[s]
  return e ? e[l === 'en' ? 0 : 1] : s
}
export function useT() {
  const l = useLang()
  return (s: string) => tr(l, s)
}
